// Helper to generate keyframe arrays for 5 sequential logo slots in a 100% timeline
function getSlotAnimation(slotIndex: number) {
  // 5 slots: active windows at 0-16%, 20-36%, 40-56%, 60-76%, 80-96%
  const numSlots = 5;
  const opacity: number[] = [];
  const y: number[] = [];
  const scale: number[] = [];
  const filter: string[] = [];
  const times: number[] = [];

  // Generate steps for entering, holding, and exiting each slot
  for (let i = 0; i < numSlots; i++) {
    const isCurrent = i === slotIndex;
    const startT = (i / numSlots);
    const holdT = startT + 0.15;
    const exitT = startT + 0.18;

    times.push(startT, holdT, exitT);
    opacity.push(isCurrent ? 1 : 0, isCurrent ? 1 : 0, 0);
    y.push(isCurrent ? 0 : 4, isCurrent ? 0 : 4, 4);
    scale.push(isCurrent ? 1 : 0.95, isCurrent ? 1 : 0.95, 0.95);
    filter.push(isCurrent ? "blur(0px)" : "blur(10px)", isCurrent ? "blur(0px)" : "blur(10px)", "blur(10px)");
  }

  // Close loop back to 1.0 time
  times.push(1);
  const isFirstSlot = slotIndex === 0;
  opacity.push(isFirstSlot ? 1 : 0);
  y.push(isFirstSlot ? 0 : 4);
  scale.push(isFirstSlot ? 1 : 0.95);
  filter.push(isFirstSlot ? "blur(0px)" : "blur(10px)");

  return { opacity, y, scale, filter, times };
}

export default function BrandLogoGrid() {
  const transition: Transition = {
    duration: 25,
    ease: "linear",
    repeat: Infinity,
  };

  return (
    <motion.div className="grid h-auto w-full grid-cols-5 divide-x divide-zinc-200 border-b border-zinc-200">
      {columnSequences.map((sequence, colIndex) => {
        return (
          <motion.div
            key={colIndex}
            className="relative col-span-1 flex h-20 w-full items-center justify-center overflow-hidden"
          >
            {sequence.map((LogoComponent, slotIndex) => {
              const anim = getSlotAnimation(slotIndex);

              return (
                <motion.div
                  key={slotIndex}
                  animate={{
                    opacity: anim.opacity,
                    y: anim.y,
                    scale: anim.scale,
                    filter: anim.filter,
                  }}
                  transition={{
                    ...transition,
                    times: anim.times,
                    delay: colIndex * 0.4,
                  }}
                  className="absolute inset-0 m-auto h-fit w-fit opacity-0"
                >
                  <LogoComponent />
                </motion.div>
              );
            })}
          </motion.div>
        );
      })}
    </motion.div>
  );
}

